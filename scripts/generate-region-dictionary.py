"""Generate the bundled ABR dictionary from approved, SHA-pinned offline evidence."""
import csv, hashlib, json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'design/調査データ/japan-municipality-274'
manifest = json.loads((BASE / 'manifest.json').read_text())
sources = manifest['sources'][:3]
for source in sources:
    assert hashlib.sha256((BASE / source['file']).read_bytes()).hexdigest() == source['fileSha256']
def read(name):
    with (BASE / name).open(encoding='utf-8-sig', newline='') as file:
        return list(csv.DictReader(file))
cities = read('mt_city_all.csv')
positions = {row['lg_code']: row for row in read('mt_city_pos_all.csv')}
assert len(cities) == len(positions) == 1918
version = 'abr-20261011-' + hashlib.sha256(''.join(s['fileSha256'] for s in sources).encode()).hexdigest()[:16]
rows = []
for city in sorted(cities, key=lambda row: row['lg_code']):
    position = positions[city['lg_code']]
    lat, lon = float(position['rep_lat']), float(position['rep_lon'])
    assert position['rep_srid'] == 'EPSG:6668' and math.isfinite(lat) and math.isfinite(lon)
    assert 20 < lat < 50 and 120 < lon < 155
    assert not city['ablt_date'] or city['ablt_date'] > '2026-10-11'
    rows.append({**{key:city[key] for key in ['lg_code','pref','county','city','ward','pref_kana','county_kana','city_kana','ward_kana']}, 'latitude':lat,'longitude':lon})
output = '// Generated by scripts/generate-region-dictionary.py; do not edit.\n'
output += 'export const datasetVersion = ' + json.dumps(version) + ';\n'
output += 'export const municipalityRows = ' + json.dumps(rows, ensure_ascii=False, separators=(',',':')) + ';\n'
target = ROOT / 'apps/api/src/domains/region/data/municipalities.ts'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Regenerate bundled dictionary'
else:
    target.write_text(output)
print(f'ABR dictionary: {version}, {len(rows)} municipalities verified')
